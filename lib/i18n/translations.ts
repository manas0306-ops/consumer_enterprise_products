/**
 * Translation helper with graceful fallback to English and missing key handling
 */
export function translate(
  locale: string,
  namespace: TranslationNamespace,
  key: string
): { text: string; isFallback: boolean } {
  const normalizedLocale = TRANSLATIONS[locale] ? locale : 'en-US';
  const dict = TRANSLATIONS[normalizedLocale]?.[namespace];
  if (dict && dict[key]) {
    return { text: dict[key], isFallback: false };
  }

  // Fallback to English dictionary
  const fallbackDict = TRANSLATIONS['en-US']?.[namespace];
  if (fallbackDict && fallbackDict[key]) {
    return { text: fallbackDict[key], isFallback: normalizedLocale !== 'en-US' };
  }

  return { text: key, isFallback: true };
}
